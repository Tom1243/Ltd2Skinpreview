        if not item:
            return
        self.selected_id = item['id']
        mode, aspect = skin_options(item)
        self._loading_skin_settings = True
        self.preview_mode.set(mode)
        self.keep_aspect.set(aspect)
        self._loading_skin_settings = False
        path = self.item_path(item)
        self.preview_source = None
        self.preview_message = ''
        if not path.is_file():
            self.preview_message = 'Saved file is missing'
            self.info_label.configure(text='')
            self.schedule_preview()
            return
        try:
            if item['extension'] in ('.png', '.gif'):
                with Image.open(path) as source:
                    image = source.convert('RGBA')
                    dimensions = source.size
            else:
                image = self.webm_frame(path)
                dimensions = image.size if image is not None else None
            if image is not None:
                self.preview_source = image
            else:
                self.preview_message = 'WEBM preview needs FFmpeg in PATH.\nThe file can still be installed.'
            self.info_label.configure(text=f"{item['name']}  •  {item['extension'].upper()[1:]}"
                                      + (f'  •  {dimensions[0]} × {dimensions[1]}' if dimensions else ''))
        except Exception as exc:
            self.preview_message = f'Preview unavailable:\n{exc}'
            self.info_label.configure(text=item['name'])
        self.schedule_preview()
        if item['extension'] in ('.gif', '.webm') and self.preview_source is not None:
            self.start_animation(path, item['extension'])

