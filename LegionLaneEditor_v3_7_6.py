    def import_skin(self):
        filename = filedialog.askopenfilename(parent=self, title='Import skin',
                    filetypes=[('Lane skins', '*.png *.webm *.gif'), ('PNG', '*.png'), ('WebM', '*.webm'), ('GIF', '*.gif')])
        if not filename:
            return
        source = Path(filename)
        extension = source.suffix.lower()
        if extension not in EXTENSIONS:
            messagebox.showerror('Unsupported file', 'Import a PNG, WEBM, or GIF file.')
            return
        name = simpledialog.askstring('Skin name', 'Name this skin:',
                                      initialvalue=source.stem, parent=self)
        if not name or not name.strip():
            return
        identifier = uuid.uuid4().hex
        target = LIBRARY_DIR / (identifier + extension)
        try:
            shutil.copy2(source, target)
            entry = {'id': identifier, 'name': name.strip(), 'extension': extension}
            self.library.append(entry)
            write_json(LIBRARY_FILE, self.library)
        except OSError as exc:
            target.unlink(missing_ok=True)
            if self.library and self.library[-1].get('id') == identifier:
                self.library.pop()
            messagebox.showerror('Import failed', str(exc))
            return
        self.refresh_library(identifier)
        self.status.set(f'Imported {name.strip()} into AppData library. Game files unchanged.')

