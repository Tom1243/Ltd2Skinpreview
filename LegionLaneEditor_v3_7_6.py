    def apply_skins(self):
        folder = self.get_game_folder()
        if folder is None:
            return
        build = self.choice_item(self.build_choice.get())
        battle = self.choice_item(self.battle_choice.get())
        # Validate all selected source files before touching the game folder.
        planned = {}
        for prefix, item in (('lane', build), ('lane_battle', battle)):
            if item is None:
                continue
            source = self.item_path(item)
            if not source.is_file():
                messagebox.showerror('Missing skin', f"Saved file for '{item['name']}' is missing.")
                return
            planned[prefix + ('.webm' if item['extension'] == '.gif' else item['extension'])] = (source, item)

        if not messagebox.askyesno('Apply skins',
                'Replace the active game lane configuration?\n\n'
                'All four possible lane.png/webm and lane_battle.png/webm files '
                'will be cleared, then your selected skins installed.\n\n'
                'Your AppData skin library will not be changed.'):
            return

        # Convert into a temporary directory BEFORE touching any game files.
        # The game folder is only modified after every conversion succeeds.
        token = uuid.uuid4().hex
        staged = {}
        backups = {}
        installed = []
        try:
            with tempfile.TemporaryDirectory(prefix='legion_lane_export_') as work:
                for name, (source, item) in planned.items():
                    converted = Path(work) / name
                    mode, aspect = skin_options(item)
                    if item['extension'] == '.png':
                        convert_png(source, converted, mode, aspect)
                    else:
                        convert_webm(source, converted, mode, aspect)
                    temp = folder / f'.lane_editor_stage_{token}_{name}'
                    shutil.copy2(converted, temp)
                    staged[name] = temp

            # Back up ALL FOUR filenames, even when only one phase is selected.
            for name in GAME_SKIN_FILES:
                original = folder / name
                if original.exists():
                    backup = folder / f'.lane_editor_backup_{token}_{name}'
                    original.replace(backup)
                    backups[name] = backup

            for name, temp in staged.items():
                temp.replace(folder / name)
                installed.append(name)

        except Exception as exc:
            # Restore the original configuration if copying or installing fails.
            rollback_errors = []
            for name in installed:
                try:
                    (folder / name).unlink(missing_ok=True)
                except OSError as error:
                    rollback_errors.append(str(error))
            for name, backup in backups.items():
                try:
                    backup.replace(folder / name)
                except OSError as error:
                    rollback_errors.append(str(error))
            detail = f'Installation failed: {exc}'
            if rollback_errors:
                detail += '\n\nSome files could not be restored:\n' + '\n'.join(rollback_errors)
            messagebox.showerror('Apply failed', detail)
            self.status.set('Apply failed; previous skins restored where possible.')
            return
        finally:
            for temp in staged.values():
                try:
                    temp.unlink(missing_ok=True)
                except OSError:
                    pass

        # Only delete backups after the new configuration is installed.
        cleanup_errors = []
        for backup in backups.values():
            try:
                backup.unlink(missing_ok=True)
            except OSError as exc:
                cleanup_errors.append(str(exc))
        self.status.set('Applied converted skin configuration. Both phases synchronized.')
        if cleanup_errors:
            messagebox.showwarning('Applied with warning',
                'Skins installed, but temporary backup cleanup failed:\n' + '\n'.join(cleanup_errors))


