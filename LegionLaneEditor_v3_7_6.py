def convert_png(source, destination, mode, aspect):
    width, height = 2000, 4000
    with Image.open(source) as original:
        artwork = original.convert('RGBA')
    if mode == 'Fit':
        left, right, top, bottom = FIT_PADDING
        inner_w, inner_h = width - left - right, height - top - bottom
        if aspect:
            factor = min(inner_w / artwork.width, inner_h / artwork.height)
            target_w, target_h = max(1, round(artwork.width * factor)), max(1, round(artwork.height * factor))
        else:
            target_w, target_h = inner_w, inner_h
        artwork = artwork.resize((target_w, target_h), Image.Resampling.LANCZOS)
        output = Image.new('RGBA', (width, height), (0, 0, 0, 0))
        output.alpha_composite(artwork, (left + (inner_w - target_w) // 2,
                                         top + (inner_h - target_h) // 2))
    elif aspect:
        output = ImageOps.fit(artwork, (width, height), method=Image.Resampling.LANCZOS)
    else:
        output = artwork.resize((width, height), Image.Resampling.LANCZOS)
    output.save(destination, 'PNG')


def convert_webm(source, destination, mode, aspect):
    ffmpeg = shutil.which('ffmpeg')
    if not ffmpeg:
        raise RuntimeError('FFmpeg is required to convert WebM skins. Install FFmpeg and add it to PATH.')
    # 1000x2000 video output, proportional to the PNG padding preset.
    if mode == 'Fit':
        if aspect:
            filt = ('scale=934:1570:force_original_aspect_ratio=decrease:flags=lanczos,'
                    'format=yuva420p,pad=934:1570:(ow-iw)/2:(oh-ih)/2:color=black@0,'
                    'pad=1000:2000:33:180:color=black@0,format=yuva420p')
        else:
            filt = ('scale=934:1570:flags=lanczos,format=yuva420p,'
                    'pad=1000:2000:33:180:color=black@0,format=yuva420p')
    elif aspect:
        filt = ('scale=1000:2000:force_original_aspect_ratio=increase:flags=lanczos,'
                'crop=1000:2000,format=yuva420p')
    else:
        filt = 'scale=1000:2000:flags=lanczos,format=yuva420p'
    # Same no-prompt FFmpeg pipeline as the supplied cg.bat:
    # 30 fps, Lanczos resizing, VP8 yuva420p, auto-alt-ref disabled.
    command = [ffmpeg, '-hide_banner', '-loglevel', 'error', '-y', '-i', str(source),
               '-map', '0:v:0', '-an', '-vf', 'fps=30,' + filt, '-c:v', 'libvpx', '-pix_fmt', 'yuva420p',
               '-auto-alt-ref', '0', '-deadline', 'good', '-cpu-used', '3', '-b:v', '0',
               '-crf', '12', str(destination)]
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0 or not destination.is_file() or destination.stat().st_size == 0:
        raise RuntimeError('FFmpeg conversion failed: ' + (result.stderr[-1600:] or 'Unknown error'))


def read_json(path, default):
    try:
        value = json.loads(path.read_text(encoding='utf-8'))
        return value if isinstance(value, type(default)) else default
    except (OSError, ValueError):
        return default


def write_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + '.tmp')
    temporary.write_text(json.dumps(data, indent=2), encoding='utf-8')
    temporary.replace(path)


def drives():
    return [Path(f'{letter}:/') for letter in string.ascii_uppercase if Path(f'{letter}:/').is_dir()]


def valid_lane_folder(folder):
    try:
        p = Path(folder)
        return (p.is_dir() and p.name.lower() == 'laneskin'
                and p.parent.name.lower() == 'streamingassets'
                and p.parent.parent.name.lower() == 'legion td 2_data')
    except (OSError, ValueError):
        return False


def steam_libraries():
    roots = set()
    for drive in drives():
        for relative in ('Program Files (x86)/Steam', 'Program Files/Steam',
                         'Steam', 'Games/Steam', 'SteamLibrary'):
            root = drive / relative
            if root.is_dir():
                roots.add(root)
                vdf = root / 'steamapps' / 'libraryfolders.vdf'
                if vdf.is_file():
                    try:
                        content = vdf.read_text(encoding='utf-8-sig', errors='replace')
                        for item in re.findall(r'"path"\s+"([^"]+)"', content):
                            roots.add(Path(item.replace('\\\\', '\\')))
                    except OSError:
                        pass
    return roots


def detect_lane_folder():
    candidates = []
    for drive in drives():
        for relative in ('Games/LegionTD2', 'Games/Legion TD 2',
                         'Epic Games/LegionTD2', 'Epic Games/Legion TD 2',
                         'Program Files/Epic Games/LegionTD2',
                         'Program Files (x86)/Steam/steamapps/common/Legion TD 2',
                         'SteamLibrary/steamapps/common/Legion TD 2',
                         'Steam/steamapps/common/Legion TD 2'):
            candidates.append(drive / relative / SUFFIX)
    for root in steam_libraries():
        for name in ('Legion TD 2', 'LegionTD2'):
            candidates.append(root / 'steamapps' / 'common' / name / SUFFIX)
    for candidate in dict.fromkeys(candidates):
        if valid_lane_folder(candidate):
            return candidate
    return None


def perspective_skin(image, top_inset, depth, skew=0.0):
    """Warp a transparent RGBA skin into a trapezoid, leaving backdrop untouched."""
    if top_inset <= 0.00001 and depth <= 0.00001 and abs(skew) <= 0.00001:
        return image
    w, h = image.size
    inset = w * min(0.45, max(0.0, top_inset))
    # Output corners (trapezoid) -> source corners (full rectangle).
    # Depth is independent of narrowing: the distant edge moves downward
    # while the near/bottom edge remains anchored.
    top_y = (h - 1) * min(0.65, max(0.0, depth))
    # Shift the top edge independently, so left and right red boundaries
    # can both align without changing the overall top width.
    shift = w * min(0.4, max(-0.4, skew))
    left_top = min(w - 2, max(0, inset + shift))
    right_top = max(left_top + 1, min(w - 1, w - 1 - inset + shift))
    correspondences = [
        (left_top, top_y, 0, 0), (right_top, top_y, w - 1, 0),
        (w - 1, h - 1, w - 1, h - 1), (0, h - 1, 0, h - 1),
    ]
    equations = []
    for x, y, u, v in correspondences:
        equations.append([x, y, 1, 0, 0, 0, -u*x, -u*y, u])
        equations.append([0, 0, 0, x, y, 1, -v*x, -v*y, v])
    for col in range(8):
        pivot = max(range(col, 8), key=lambda row: abs(equations[row][col]))
        equations[col], equations[pivot] = equations[pivot], equations[col]
        div = equations[col][col]
        if abs(div) < 1e-12:
            return image
        equations[col] = [val / div for val in equations[col]]
        for row in range(8):
            if row != col:
                factor = equations[row][col]
                equations[row] = [a - factor*b for a, b in zip(equations[row], equations[col])]
    coefficients = [row[8] for row in equations]
    return image.transform((w, h), Image.Transform.PERSPECTIVE, coefficients,
                           resample=Image.Resampling.BICUBIC, fillcolor=(0, 0, 0, 0))


